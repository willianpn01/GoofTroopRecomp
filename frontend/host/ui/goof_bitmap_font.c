uint8_t goof_font_row(char c, int row) {
  unsigned u = (unsigned char)c;
  if (u < GOOF_FONT_FIRST || u >= GOOF_FONT_FIRST + GOOF_FONT_GLYPHS) u = '?';
  if (row < 0 || row >= GOOF_FONT_H) return 0;
  const char *r = kGlyphs[u - GOOF_FONT_FIRST][row];
  uint8_t bits = 0;
  for (int x = 0; x < GOOF_FONT_W; x++)
    if (r[x] == '#') bits |= (uint8_t)(1u << (GOOF_FONT_W - 1 - x));
  return bits;
}
